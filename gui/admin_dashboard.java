public void loadDashboardData() {
    // 1. Load Counter Statistics
    try (Connection conn = dbconnection.getConnection()) {
        
        // Total Tickets
        try (PreparedStatement pst = conn.prepareStatement("SELECT COUNT(*) FROM tbl_tickets");
             ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {
                // Replace totalLabel with your actual JLabel variable name for the Total count
                totalLabel.setText(String.valueOf(rs.getInt(1)));
            }
        }

        // Pending Tickets
        try (PreparedStatement pst = conn.prepareStatement("SELECT COUNT(*) FROM tbl_tickets WHERE status = 'Pending'");
             ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {
                pendingLabel.setText(String.valueOf(rs.getInt(1)));
            }
        }

        // In Progress Tickets
        try (PreparedStatement pst = conn.prepareStatement("SELECT COUNT(*) FROM tbl_tickets WHERE status = 'In Progress'");
             ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {
                inProgressLabel.setText(String.valueOf(rs.getInt(1)));
            }
        }

        // Resolved Tickets
        try (PreparedStatement pst = conn.prepareStatement("SELECT COUNT(*) FROM tbl_tickets WHERE status = 'Resolved'");
             ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {
                resolvedLabel.setText(String.valueOf(rs.getInt(1)));
            }
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading dashboard statistics: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }

    // 2. Load Recent Tickets into the Table
    String[] columns = {"Ticket ID", "Student Name", "Building", "Status", "Date Submitted"};
    DefaultTableModel model = new DefaultTableModel(columns, 0);

    String sql = "SELECT * FROM tbl_tickets ORDER BY ticket_id DESC LIMIT 10";

    try (Connection conn = dbconnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        int counter = 1;
        while (rs.next()) {
            String displayTicketId = "TID-" + String.format("%04d", counter++);
            String name = rs.getString("name");
            String building = rs.getString("building");
            String status = rs.getString("status");
            if (status == null || status.isEmpty()) status = "Pending";
            String dateSubmitted = rs.getString("date_submitted");

            model.addRow(new Object[]{displayTicketId, name, building, status, dateSubmitted});
        }

        // Replace jTable1 with your actual JTable variable name for the recent tickets table
        jTable1.setModel(model);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading recent tickets: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }
}

