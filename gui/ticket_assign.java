   private void loadTicketDescription(int dbId) {
    String sql = "SELECT description FROM tbl_tickets WHERE id = ?";
    
    try (Connection conn = dbconnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {
         
        pst.setInt(1, dbId);
        try (ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {
                String desc = rs.getString("description");
                // Replace jTextArea1 with your actual JTextArea variable name for the description box
                jTextArea1.setText(desc);
                jTextArea1.setEditable(false); // Make it read-only so admins can view it safely
                jTextArea1.setLineWrap(true);
                jTextArea1.setWrapStyleWord(true);
            }
        }
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading description: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }
   }
   
