    private void btn1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn1ActionPerformed
       String uN, pW, query;
           
try{
    Class.forName("com.mysql.cj.jdbc.Driver"); // TIG REGISTER
    String url = "jdbc:MySql://localhost:3306/its_ticketingsystem"; 
    String user = "root";  // SECURITY CHECK
    String pass = "";
    
    Connection con = DriverManager.getConnection(url, user, pass); //CONNECTION OF DATABASE OR ELISTA ANG MGA VARIABLE NAMES 
    Statement st = con.createStatement(); // MAG CREATE UG STATEMENT PARA MABUTANG SA DATABASE
    
    if("".equals(username.getText())){
        JOptionPane.showMessageDialog(this, "Username is required", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }else  if("".equals(password.getText())){              // VALIDATION. GIKAN SA VARIABLE ANG PASSWORD 
        JOptionPane.showMessageDialog(this, "Password is required", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }else{
        uN = username.getText();
        pW = password.getText();
        query = "INSERT INTO tbl_users (uname, password) "
                + "VALUES ('"+uN+"','"+pW+"')";
        st.executeUpdate(query);
        con.close();
    }
    JOptionPane.showMessageDialog(this, "Account Created Successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
    
    loginfinal login = new loginfinal();
    login .setVisible(true);
    this.dispose();

    
}catch(Exception e) {
    System.out.println("Error " + e.getMessage());
}
    }//GEN-LAST:event_btn1ActionPerformed

