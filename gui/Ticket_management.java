    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
int selectedRow = jTable1.getSelectedRow();
if (selectedRow == -1) {
    JOptionPane.showMessageDialog(this, "Please select a ticket to archive.", "Warning", JOptionPane.WARNING_MESSAGE);
    return;
}

// Automatically search the selected row for "Resolved" or "Completed" status so column index never matters
String status = "";
for (int i = 0; i < jTable1.getColumnCount(); i++) {
    Object val = jTable1.getValueAt(selectedRow, i);
    if (val != null) {
        String text = val.toString().trim();
        if (text.equalsIgnoreCase("Resolved") || text.equalsIgnoreCase("Completed") || text.equalsIgnoreCase("Closed")) {
            status = text;
            break;
        }
    }
}

// Fallback: if loop didn't catch it, grab it from a specific column index or check database
if (status.isEmpty() && jTable1.getColumnCount() > 5) {
    Object fallbackVal = jTable1.getValueAt(selectedRow, 5);
    if (fallbackVal != null) status = fallbackVal.toString().trim();
}

// STRICT VALIDATION: Allow archiving ONLY if the status is Resolved/Completed
if (status.isEmpty() || (!status.equalsIgnoreCase("Resolved") && !status.equalsIgnoreCase("Completed") && !status.equalsIgnoreCase("Closed"))) {
    JOptionPane.showMessageDialog(this, "Only tickets with a 'Resolved' status can be archived. (Current status detected: '" + status + "')", "Action Denied", JOptionPane.WARNING_MESSAGE);
    return;
}

// FIXED: Grab the true database primary key from column 0
int dbTicketId = Integer.parseInt(jTable1.getValueAt(selectedRow, 0).toString());

String insertSql = "INSERT INTO tbl_archived_tickets SELECT * FROM tbl_tickets WHERE id = ?";
String deleteSql = "DELETE FROM tbl_tickets WHERE id = ?";

try (Connection conn = dbconnection.getConnection();
     PreparedStatement pstInsert = conn.prepareStatement(insertSql);
     PreparedStatement pstDelete = conn.prepareStatement(deleteSql)) {

    // 1. Copy to archive table using the correct numeric id from column 0
    pstInsert.setInt(1, dbTicketId);
    pstInsert.executeUpdate();

    // 2. Remove from active tickets table using the correct numeric id from column 0
    pstDelete.setInt(1, dbTicketId);
    pstDelete.executeUpdate();

    JOptionPane.showMessageDialog(this, "Ticket successfully archived.");
    
    // Refresh your active tickets table view
    loadTicketsFromDatabase(); 

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error archiving ticket: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_jButton5ActionPerformed

