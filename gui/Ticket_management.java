    public void loadAllTicketsForAdmin() {
    String[] columns = {"DB ID", "Ticket ID", "Student Name", "Student ID", "Building", "Issue Type", "Status", "Date Submitted"};
    DefaultTableModel model = new DefaultTableModel(columns, 0);

    String sql = "SELECT * FROM tbl_tickets ORDER BY ticket_id DESC";

    try (Connection conn = dbconnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        int counter = 1;
        while (rs.next()) {
            int dbTicketId = rs.getInt("id");
            String displayTicketId = "TID-" + String.format("%04d", counter++);
            String name = rs.getString("name");
            String studentId = rs.getString("student_id");
            String building = rs.getString("building");
            String issueType = rs.getString("issue_type");
            String status = rs.getString("status");
            if (status == null || status.isEmpty()) status = "Pending";
            String dateSubmitted = rs.getString("date_submitted");

            model.addRow(new Object[]{dbTicketId, displayTicketId, name, studentId, building, issueType, status, dateSubmitted});
        }

        // Replace jTable1 with your actual table variable name
        jTable1.setModel(model);

        // Hide the database ID column (column 0)
        jTable1.getColumnModel().getColumn(0).setMinWidth(0);
        jTable1.getColumnModel().getColumn(0).setMaxWidth(0);
        jTable1.getColumnModel().getColumn(0).setWidth(0);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading tickets: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }
}
    
