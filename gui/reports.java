    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed
    int total = 0;
    int pending = 0;
    int inProgress = 0;
    int resolved = 0;
    int closed = 0;

    // 1. Get dates from the new date choosers
    java.util.Date selectedDateFrom = dateChooserFrom.getDate();
    java.util.Date selectedDateTo = dateChooserTo.getDate();

    // 2. Validation
    if (selectedDateFrom == null || selectedDateTo == null) {
        JOptionPane.showMessageDialog(this, "Please select both 'Date From' and 'Date To' from the calendar.", "Warning", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 3. Format dates for MySQL queries
    java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
    String dateFromStr = sdf.format(selectedDateFrom) + " 00:00:00";
    String dateToStr = sdf.format(selectedDateTo) + " 23:59:59";

    // 4. SQL Queries for Active and Archived records with date filtering
    String activeSql = "SELECT status, COUNT(*) FROM tbl_tickets WHERE date_submitted BETWEEN ? AND ? GROUP BY status";
    String archivedSql = "SELECT status, COUNT(*) FROM tbl_archived_tickets WHERE date_submitted BETWEEN ? AND ? GROUP BY status";

    try (Connection conn = dbconnection.getConnection()) {
        
        // Fetch active tickets counts
        try (PreparedStatement pst = conn.prepareStatement(activeSql)) {
            pst.setString(1, dateFromStr);
            pst.setString(2, dateToStr);
            try (ResultSet rs = pst.executeQuery()) {
                while (rs.next()) {
                    String status = rs.getString(1);
                    int count = rs.getInt(2);
                    total += count;

                    if (status != null) {
                        if (status.equalsIgnoreCase("Pending")) pending += count;
                        else if (status.equalsIgnoreCase("In Progress")) inProgress += count;
                        else if (status.equalsIgnoreCase("Resolved")) resolved += count;
                        else if (status.equalsIgnoreCase("Closed")) closed += count;
                    }
                }
            }
        }

        // Fetch archived tickets counts
        try (PreparedStatement pstArch = conn.prepareStatement(archivedSql)) {
            pstArch.setString(1, dateFromStr);
            pstArch.setString(2, dateToStr);
            try (ResultSet rsArch = pstArch.executeQuery()) {
                while (rsArch.next()) {
                    String status = rsArch.getString(1);
                    int count = rsArch.getInt(2);
                    total += count;

                    if (status != null) {
                        if (status.equalsIgnoreCase("Pending")) pending += count;
                        else if (status.equalsIgnoreCase("In Progress")) inProgress += count;
                        else if (status.equalsIgnoreCase("Resolved")) resolved += count;
                        else if (status.equalsIgnoreCase("Closed")) closed += count;
                    }
                }
            }
        }

        // Update the report summary labels
TotalTickets.setText(String.valueOf(total));
Pending.setText(String.valueOf(pending));
InProgress.setText(String.valueOf(inProgress));
Resolved.setText(String.valueOf(resolved));
Closed.setText(String.valueOf(closed));

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error generating report: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton8ActionPerformed

