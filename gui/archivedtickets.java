    private void loadArchivedTickets() {
    String sql = "SELECT * FROM tbl_archived_tickets";
    
    try (Connection conn = dbconnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {
         
        // Use DefaultTableModel to populate your table
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) TableArchived.getModel();
        model.setRowCount(0); // Clear existing rows
        
        while (rs.next()) {
            Object[] row = {
                rs.getString("ticket_id"),
                rs.getString("name"),
                rs.getString("student_id"),
                rs.getString("building"),
                rs.getString("issue_type"),
                rs.getString("status"),
                rs.getString("date_submitted")
            };
            model.addRow(row);
        }
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading archived tickets: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }
    }
    
